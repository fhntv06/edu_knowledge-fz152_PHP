## КОГДА ЗАКОН НЕ РАБОТАЕТ (исключения из правил)
**Для обычного человека это важно:** Есть ситуации, когда можно обрабатывать чужие данные, и 152-ФЗ вас не накажет.
**Закон не распространяется на 3 ситуации при сборе персональных данных:**
1. Если собираются данные для личных и семейных нужд;
2. Если данные собираются в документах Арховного фонда РФ и *регулируется законодательсвом об архивном деле РФ*;
3. Если данные относятся к государственной тайне, то регулируются *Законом РФ от 21.07.1993 N 5485-1 \\\"О государственной тайне\\\"*
## ОТДЕЛЬНАЯ ПЕСЕНКА ПРО СУДЕЙ
**Обычный смысл:** Когда суды публикуют информацию о своих делах (решения, приговоры), там есть персональные данные (ФИО судей, сторон). **Эти отношения НЕ регулируются 152-ФЗ**.
Они подчиняются специальному закону № 262-ФЗ «О доступе к информации о деятельности судов».

